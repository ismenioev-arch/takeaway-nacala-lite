/**
 * As cores não são valores fixos: são variáveis CSS definidas em
 * `src/index.css`, em HSL e sem a função `hsl()` à volta. É isso que permite
 * escrever `bg-primary/20` — o Tailwind injecta a opacidade na própria cor —
 * e é o que faz o tema escuro funcionar sem duplicar classes.
 */
